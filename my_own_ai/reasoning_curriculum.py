"""Source-grounded reasoning lessons from chapterless numbered treatises.

Answers are selected verbatim from the author's own numbered paragraphs. This
is supervised extraction and premise/consequence practice, not a claim that an
untrained model can infer arbitrary novel philosophy.
"""
from collections import Counter
from hashlib import sha256
import json
from pathlib import Path
import re

from .corpus import collect_documents

NUMBERED = re.compile(r"^\s*\[(\d+)\]\s+", re.S)
DEFINITION = re.compile(r"\b(?:means|is defined as|is therefore|is consequently|names|denotes|refers to)\b", re.I)
CONSEQUENCE = re.compile(r"\b(?:therefore|consequently|hence|thus|it follows|means that)\b", re.I)
MATH = re.compile(r"[∂∑∈≠≤≥=Φτ]|(?<![A-Za-z])(?:Xi,t|X\(i,t\))")
WORDS = re.compile(r"\S+")


def segments(text):
    # PDF line wraps are visual formatting, not sentence/paragraph boundaries.
    prose = re.sub(r"\s+", " ", text.strip())
    return [s.strip() for s in
            re.split(r"(?<=[.!?])\s+(?=[A-Z“\"'\[])", prose) if s.strip()]


def extract_lessons(text, *, source_id, max_answer_chars=190):
    match = NUMBERED.match(text)
    if not match:
        return []
    number = int(match.group(1))
    lines = segments(text[match.end():])
    if not lines:
        return []
    result = []
    def add(kind, prompt, answer):
        answer = answer.strip()
        if not 15 <= len(answer) <= max_answer_chars:
            return
        # Every target must be an exact extract from the actual source text,
        # modulo PDF wrap whitespace. No invented logical consequences.
        original = re.sub(r"\s+", " ", text)
        if answer not in original:
            return
        key = sha256((source_id + "\0" + kind + "\0" + prompt + "\0" + answer).encode()).hexdigest()
        result.append({"id": key[:24], "question": prompt, "answer": answer,
                       "kind": kind, "paragraph": number, "source": source_id})
    for sentence in lines:
        if len(sentence) <= max_answer_chars:
            if DEFINITION.search(sentence):
                add("definition", f"State the author's definition or identity claim in numbered paragraph [{number}].",
                    sentence)
                break
    # Premise/consequence instruction uses a *source passage*, not an
    # unverified proposition generated by a teacher model.
    for prev, current in zip(lines, lines[1:]):
        if (CONSEQUENCE.search(current) and
            25 <= len(prev) <= max_answer_chars and 20 <= len(current) <= max_answer_chars):
            add("derivation", f"In paragraph [{number}], the author writes: {prev}\n"
                "What consequence does the author give?", current)
            break
    for line in text.splitlines():
        piece = line.strip()
        if 12 <= len(piece) <= max_answer_chars and MATH.search(piece):
            add("mathematical", f"Reproduce one mathematical expression from paragraph [{number}].",piece)
            break
    # Explicit reading/comprehension instruction, not an unsupported semantic
    # paraphrase or manufactured counterfactual.
    for sentence in lines[:2]:
        if 25 <= len(sentence) <= max_answer_chars:
            add("proposition", f"What proposition does numbered paragraph [{number}] state?",
                sentence)
            break
    # Deduplicate question IDs within paragraph, preserving source order.
    unique = {}
    for row in result:
        unique.setdefault((row["question"], row["answer"]),row)
    return list(unique.values())


def create_reasoning_lessons(prepared, destination, *, limit_per_split=800):
    source, output = Path(prepared).resolve(), Path(destination).resolve()
    if output.exists() or output == source or output.is_relative_to(source):
        raise ValueError("Reasoning lessons must use a new separate destination")
    manifest = json.loads((source / "manifest.json").read_text())
    if manifest.get("format") != "approved_books_v1" or manifest.get("chunk_unit") != "numbered_paragraph":
        raise ValueError("Numbered-paragraph approved corpus required")
    result = {}
    pool = {}
    for split in ("train", "validation", "test"):
        lessons = []
        for doc in collect_documents(source / split):
            lessons.extend(extract_lessons(doc["text"], source_id=doc["source"]))
        pool[split] = lessons
    # Question+answer exact collision cannot leak across partitions.
    normalized = {}
    for split, lessons in pool.items():
        for item in lessons:
            normalized.setdefault(" ".join(item["question"].casefold().split()),set()).add(split)
    excluded = {key for key, locations in normalized.items() if len(locations)>1}
    output.mkdir(parents=True)
    for split, lessons in pool.items():
        filtered, used = [], set()
        for row in lessons:
            key = " ".join(row["question"].casefold().split())
            if key in excluded or key in used:
                continue
            used.add(key)
            filtered.append({k:row[k] for k in ("id","question","answer")})
            if len(filtered) == limit_per_split:
                break
        if not filtered:
            raise ValueError(f"No grounded reasoning lessons for {split}")
        (output / f"{split}.json").write_text(json.dumps(filtered,ensure_ascii=False,indent=2))
        result[split]={"total":len(filtered),
                       "kinds":dict(Counter(row["kind"] for row in lessons))}
    summary={"format":"numbered_reasoning_lessons_v1",
             "source_manifest_sha256":sha256((source/"manifest.json").read_bytes()).hexdigest(),
             "splits":result,"cross_split_prompts_excluded":len(excluded)}
    (output/"manifest.json").write_text(json.dumps(summary,indent=2))
    return summary
